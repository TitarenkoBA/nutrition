/**
 * Текст согласия на обработку персональных данных (включая данные о здоровье).
 * Один и тот же текст показывается в анкете и попадает в PDF, поэтому отправленный
 * файл служит подтверждением согласия.
 *
 * Шаблон — перед запуском покажите его юристу.
 */

export interface Operator {
  /** Имя нутрициолога (оператора персональных данных). */
  name: string;
  email: string;
  /** Полный адрес страницы политики конфиденциальности. */
  privacyUrl: string;
}

export const CONSENT_TITLE = "Согласие на обработку персональных данных";

export function consentParagraphs(subject: { fullName: string; birthDate: string }, operator: Operator): string[] {
  const who = subject.fullName.trim() || "________________________________";
  const born = subject.birthDate ? `, дата рождения ${subject.birthDate}` : "";
  return [
    `Я, ${who}${born}, в соответствии со статьями 9 и 10 Федерального закона от 27.07.2006 № 152-ФЗ «О персональных данных» свободно, своей волей и в своём интересе даю согласие ${operator.name} (далее — Оператор) на обработку моих персональных данных, указанных в настоящей анкете, в том числе специальной категории персональных данных — сведений о состоянии здоровья, а также результатов анализов, медицинских документов и фотографий, которые я направлю Оператору дополнительно.`,
    "Цель обработки: подготовка персональных рекомендаций по питанию, консультирование и связь со мной.",
    "Действия с данными: сбор, запись, систематизация, хранение, уточнение, использование, удаление и уничтожение. Данные не передаются третьим лицам.",
    `Согласие действует до достижения цели обработки или до его отзыва. Я могу отозвать согласие, направив письменное обращение на адрес ${operator.email}.`,
    `Я ознакомлен(а) с Политикой конфиденциальности: ${operator.privacyUrl}`,
  ];
}

export function formatConsentDate(iso: string): string {
  const date = iso ? new Date(iso) : null;
  if (!date || Number.isNaN(date.valueOf())) return "";
  return date.toLocaleString("ru-RU", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}
